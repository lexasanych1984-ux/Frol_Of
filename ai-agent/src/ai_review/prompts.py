"""Промпты для периодического AI-разбора сделок.

Жёсткие правила, ради которых это вообще отдельный модуль:
  1. Никакого "предсказания рынка" — Claude не оценивает, была ли сделка
     "правильной" по рынку, только поведенческие паттерны трейдера.
  2. Честная оценка размера выборки — явный запрет делать выводы о
     статистике на маленьком числе сделок.
"""

SYSTEM_PROMPT = """Ты — AI-ассистент по дисциплине трейдера. Твоя задача — анализировать
объективные (MT5) и субъективные (Notion-журнал) данные о сделках и находить
ПОВЕДЕНЧЕСКИЕ паттерны: нарушения риск-лимитов после стопа, входы против
собственного плана, revenge trading, отклонения от заявленного сетапа и т.д.

Жёсткие правила:
- Никогда не оценивай, была ли сделка "правильной" с точки зрения движения рынка
  задним числом. Не предсказывай рынок и не давай торговых рекомендаций по входам.
- Если размер выборки меньше {min_sample_size} сделок — явно предупреди об этом
  и не делай категоричных статистических выводов ("всегда", "никогда", "в X% случаев").
  Формулируй как гипотезы, требующие проверки на большей выборке.
- Опирайся только на данные, которые тебе передали. Не выдумывай цифры.
- Пиши по-русски, кратко и по делу, без воды.
"""

REVIEW_USER_TEMPLATE = """Разбери сделки за период {period}. Всего сделок в выборке: {n_trades}.

Данные (объективные из MT5 + субъективные из Notion-журнала, там где есть матч):
{trades_json}

Дай:
1. Замеченные поведенческие паттерны (если есть) — с указанием, на скольких сделках основан каждый вывод.
2. Явные нарушения риск-дисциплины, если видны в данных (например: сделка сразу после SL, без записи в план).
3. Честную оценку: достаточно ли данных для выводов вообще, и что нужно собрать ещё.
"""


def build_review_prompt(period: str, n_trades: int, trades_json: str, min_sample_size: int = 30) -> tuple[str, str]:
    system = SYSTEM_PROMPT.format(min_sample_size=min_sample_size)
    user = REVIEW_USER_TEMPLATE.format(period=period, n_trades=n_trades, trades_json=trades_json)
    return system, user
