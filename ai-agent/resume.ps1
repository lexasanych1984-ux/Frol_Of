# Возобновление бота после паузы.
#
# В этом проекте (в отличие от bybit-tradfi-bot) нет отдельных задач в Планировщике
# Windows для новостного дайджеста или dedupe-отчёта: недельный дайджест шлётся
# фоновым циклом ВНУТРИ процесса бота (src/telegram_bot/bot.py::_news_loop, пока
# бот запущен), а dedupe-отчёт запускается вручную командой `dedupe-journal`
# (CLI, не по расписанию). Поэтому возобновление — это просто запуск бота: как
# только он не запущен, автопуш дайджеста и разборов новостей не идёт вообще.
#
# Ничего не переустанавливает и не трогает .env/config.yaml.

Write-Host "Планировщика Windows для этого проекта нет — включать нечего."
Write-Host "Запускаю бота..."
Write-Host ""

Set-Location $PSScriptRoot
& '.\.venv\Scripts\python.exe' -m src.telegram_bot.bot

Write-Host ""
Write-Host "Бот остановлен."
Read-Host "Нажми Enter для выхода"
